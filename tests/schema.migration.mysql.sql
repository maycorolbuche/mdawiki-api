CREATE TABLE IF NOT EXISTS `ACESSOS_LOGS` (

  `EMAIL` varchar(150) DEFAULT NULL,
  `NAVEGADOR` longtext,
  `IP` varchar(50) DEFAULT NULL,
  `DATAHORA_LOGIN` datetime DEFAULT NULL,
  `DATAHORA_LOGOUT` datetime DEFAULT NULL,
  `UID` varchar(50) DEFAULT NULL
) ENGINE=InnoDB DEFAULT CHARSET=latin1;

CREATE TABLE IF NOT EXISTS `COMENTARIOS` (

  `ID` int(11) NOT NULL AUTO_INCREMENT,
  `NOME_URL` varchar(250) DEFAULT NULL,
  `EMAIL` varchar(150) DEFAULT NULL,
  `COMENTARIO` longtext,
  `ID_PAI` int(11) DEFAULT NULL,
  `DATAHORA` datetime DEFAULT NULL,
  PRIMARY KEY (`ID`),
  KEY `FK_COMENTARIOS_COMENTARIOS` (`ID_PAI`),
  CONSTRAINT `FK_COMENTARIOS_COMENTARIOS` FOREIGN KEY (`ID_PAI`) REFERENCES `COMENTARIOS` (`ID`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=latin1;

CREATE TABLE IF NOT EXISTS `CONFIG` (

  `CHAVE` varchar(50) NOT NULL,
  `VALOR` longtext,
  PRIMARY KEY (`CHAVE`)
) ENGINE=InnoDB DEFAULT CHARSET=latin1;

CREATE TABLE IF NOT EXISTS `CRONJOB_LOGS` (

  `ID` int(11) NOT NULL AUTO_INCREMENT,
  `EVENTO` varchar(50) DEFAULT NULL,
  `DATAHORA_INI` datetime DEFAULT NULL,
  `DATAHORA_FIM` datetime DEFAULT NULL,
  `PARAM` longtext,
  `RETORNO` longtext,
  PRIMARY KEY (`ID`)
) ENGINE=InnoDB DEFAULT CHARSET=latin1;

CREATE TABLE IF NOT EXISTS `NIVEL` (

  `NIVEL` int(11) NOT NULL,
  `DESCRICAO` varchar(50) DEFAULT NULL,
  PRIMARY KEY (`NIVEL`)
) ENGINE=InnoDB DEFAULT CHARSET=latin1;

CREATE TABLE IF NOT EXISTS `ONLINE` (

  `UID` varchar(50) NOT NULL,
  `DATAHORA_ACESSO` datetime NOT NULL,
  `DATAHORA` datetime NOT NULL COMMENT 'Data e Hora de Acesso',
  `IP` varchar(50) NOT NULL COMMENT 'IP',
  `NAVEGADOR` longtext NOT NULL COMMENT 'Navegador',
  `EMAIL` varchar(150) NOT NULL,
  `TEMPO_SESSAO` int(10) DEFAULT '30',
  PRIMARY KEY (`UID`)
) ENGINE=InnoDB DEFAULT CHARSET=latin1;

CREATE TABLE IF NOT EXISTS `PAGINAS_ACESSOS_LOGS` (

  `ID` int(11) NOT NULL AUTO_INCREMENT,
  `IDENT` varchar(50) NOT NULL,
  `NOME_URL` varchar(250) NOT NULL DEFAULT '',
  `DATAHORA` datetime DEFAULT NULL,
  `ACESSO_NUM` int(11) DEFAULT NULL,
  `NAVEGADOR` longtext,
  `IP` varchar(50) DEFAULT NULL,
  `_PARAMETROS` longtext NOT NULL,
  `_USU_LOGADO` varchar(250) DEFAULT NULL,
