import assert from 'node:assert/strict';
import { build } from 'esbuild';
const bundle = await build({entryPoints:['src/normalizeLinks.ts'],bundle:true,platform:'node',format:'esm',write:false});
const { normalizeLinks } = await import('data:text/javascript;base64,'+Buffer.from(bundle.outputFiles[0].text).toString('base64'));
const bare = normalizeLinks('<p>http://algo.teste e https://qqcoisa</p>');
assert.ok(bare.includes('href="http://algo.teste"'));
assert.ok(bare.includes('href="https://qqcoisa"'));
const renamed = normalizeLinks('<p><a href="http://antigo">http://outracoisa.</a></p>');
assert.ok(renamed.includes('href="http://outracoisa"'));
assert.ok(!renamed.includes('http://antigo'));
assert.ok(renamed.includes('target="_blank"'));
assert.ok(renamed.includes('rel="noopener noreferrer"'));
assert.ok(normalizeLinks('<a href="http://antigo"><strong>https://novo</strong></a>').includes('href="https://novo"'));
assert.ok(normalizeLinks('<a href="/pagina">https://novo</a>').includes('href="https://novo"'));
assert.ok(normalizeLinks('<a href="https://site">Rótulo</a>').includes('href="https://site"'));
assert.equal(normalizeLinks('<code>https://codigo</code>'),'<code>https://codigo</code>');
assert.equal(normalizeLinks(renamed),renamed);
console.log('Normalização de links: texto sem marcação, destino divergente, formatação e idempotência passaram.');
